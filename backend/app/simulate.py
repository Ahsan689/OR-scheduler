"""CLI: run the baseline-vs-optimized simulation and write docs/results.md.

Usage:
    python -m app.simulate --db sqlite:///path.db --out ../docs
"""

from __future__ import annotations

import argparse
from pathlib import Path

import matplotlib

matplotlib.use("Agg")

import matplotlib.pyplot as plt  # noqa: E402
from sqlalchemy import create_engine  # noqa: E402
from sqlalchemy.orm import Session  # noqa: E402

from app.core.config import get_settings  # noqa: E402
from app.schemas.simulation import SimulationResult  # noqa: E402
from app.services.disruption import EmergencyResult, simulate_emergency_handling  # noqa: E402
from app.services.simulation import run_simulation  # noqa: E402

BASELINE_COLOR = "#eb6834"
OPTIMIZED_COLOR = "#2a78d6"
REPO_ROOT = Path(__file__).resolve().parents[2]


def _idle_overtime_chart(result: SimulationResult, path: Path) -> None:
    labels = ["Idle", "Overtime"]
    baseline = [result.baseline.idle_minutes / 60, result.baseline.overtime_minutes / 60]
    optimized = [result.optimized.idle_minutes / 60, result.optimized.overtime_minutes / 60]
    x = range(len(labels))
    width = 0.35

    fig, ax = plt.subplots(figsize=(6, 4))
    ax.bar([i - width / 2 for i in x], baseline, width, label="Baseline", color=BASELINE_COLOR)
    ax.bar([i + width / 2 for i in x], optimized, width, label="Optimized", color=OPTIMIZED_COLOR)
    ax.set_xticks(list(x))
    ax.set_xticklabels(labels)
    ax.set_ylabel("Hours (full year)")
    ax.set_title("Idle & overtime: baseline vs optimized")
    ax.legend()
    ax.spines[["top", "right"]].set_visible(False)
    fig.tight_layout()
    fig.savefig(path, dpi=120)
    plt.close(fig)


def _on_time_chart(result: SimulationResult, path: Path) -> None:
    values = [result.baseline.on_time_rate * 100, result.optimized.on_time_rate * 100]
    fig, ax = plt.subplots(figsize=(4, 4))
    ax.bar(["Baseline", "Optimized"], values, color=[BASELINE_COLOR, OPTIMIZED_COLOR])
    ax.set_ylabel("On-time first-case starts (%)")
    ax.set_ylim(0, 100)
    ax.set_title("On-time starts")
    ax.spines[["top", "right"]].set_visible(False)
    fig.tight_layout()
    fig.savefig(path, dpi=120)
    plt.close(fig)


def _hours(minutes: int) -> str:
    return f"{minutes / 60:,.0f}h"


def write_report(
    result: SimulationResult, emergency: EmergencyResult, out_dir: Path
) -> Path:
    charts = out_dir / "charts"
    charts.mkdir(parents=True, exist_ok=True)
    _idle_overtime_chart(result, charts / "idle_overtime.png")
    _on_time_chart(result, charts / "on_time.png")

    b, o = result.baseline, result.optimized
    bi, oi = _hours(b.idle_minutes), _hours(o.idle_minutes)
    bo, oo = _hours(b.overtime_minutes), _hours(o.overtime_minutes)
    bt, ot = f"{b.on_time_rate * 100:.0f}%", f"{o.on_time_rate * 100:.0f}%"
    idle_chg = f"{result.idle_reduction_pct:+.1f}%"
    over_chg = f"{result.overtime_reduction_pct:+.1f}%"
    time_chg = f"{result.on_time_gain_pct_points:+.1f} pts"
    eb = _hours(emergency.baseline_overtime_minutes)
    eo = _hours(emergency.optimized_overtime_minutes)
    e_chg = f"{emergency.overtime_reduction_pct:+.1f}%"
    report = f"""# Results: baseline vs optimized

> **Synthetic data.** Generated by `simulation/`, not real patients. This is a
> portfolio demonstration, not a clinical or production system.

## Method

The same completed cases are replayed two ways under the **same actual
durations**:

- **Baseline** — the manual, surgeon-estimate schedule as it actually ran
  (recorded start/end times), including late first-case starts and the gaps
  left by same-day cancellations.
- **Optimized** — ORFlow's plan (model-predicted durations + the OR-Tools
  scheduler), executed under the same actual durations.

Both are measured the same way: idle is room time sitting empty beyond the
turnover it needs; overtime is time past the {get_settings().or_day_end_hour}:00
close; an on-time start is a room's first case beginning within the grace
window.

## Headline

| Metric | Baseline | Optimized | Improvement |
|---|---|---|---|
| Overtime (year) | {bo} | {oo} | **{over_chg}** |
| On-time first starts | {bt} | {ot} | **{time_chg}** |
| Idle gaps (year) | {bi} | {oi} | **{idle_chg}** |
| Cases / room / day | {b.avg_cases_per_room_day} | {o.avg_cases_per_room_day} | — |

Across **{result.days}** operating days and **{b.room_days}** room-days, with
**{result.cancellations}** same-day cancellations/no-shows in the dataset.

> The **overtime** and **on-time** figures are the robust headline: planning
> with predicted durations and starting each room on time removes the
> late-start cascades that drive manual-schedule overtime. The **idle** figure
> is the plan's potential — the optimized schedule runs cases back-to-back, so
> idle gaps collapse; real execution would reintroduce some idle.

![Idle and overtime](charts/idle_overtime.png)

![On-time starts](charts/on_time.png)

## Disruption handling: emergency insertion

The figures above come mostly from operational discipline (starting on time,
reclaiming cancellation gaps). This section isolates the **scheduler's own**
contribution. On the **{emergency.days}** days with an add-on emergency
(**{emergency.emergencies}** cases), the manual plan adds the emergency to the
block surgeon's already-full room; an on-call emergency can run in any room, so
the optimizer places it where there is slack. Electives stay in their rooms in
both plans, so the difference is purely the scheduler's room choice.

| Metric (emergency days) | Manual | Optimized | Improvement |
|---|---|---|---|
| Overtime | {eb} | {eo} | **{e_chg}** |

## How to reproduce

```bash
# 1. generate data, 2. import, 3. train the predictor, then:
cd backend
python -m app.simulate --db sqlite:///orflow.db --out ../docs
```

## Honest limitations

- Data is synthetic and the cases are surgeon-locked (each case is tied to its
  surgeon), so per-day room rebalancing has limited headroom; the gains here
  come mainly from starting on time, packing out cancellation gaps, and
  planning with realistic predicted durations rather than optimistic estimates.
- Total operative time per surgeon is fixed, so overtime that is driven purely
  by a surgeon's workload cannot be removed by scheduling alone.
- Not validated by clinicians; not a medical device.
"""
    path = out_dir / "results.md"
    path.write_text(report, encoding="utf-8")
    return path


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Run the ORFlow simulation.")
    parser.add_argument("--db", default=None, help="Database URL (defaults to settings).")
    parser.add_argument("--out", type=Path, default=REPO_ROOT / "docs", help="Output dir.")
    args = parser.parse_args(argv)

    url = args.db or get_settings().database_url
    engine = create_engine(url)
    with Session(engine) as session:
        result = run_simulation(session)
        emergency = simulate_emergency_handling(session)

    path = write_report(result, emergency, args.out)
    print(f"idle     {_hours(result.baseline.idle_minutes)} -> "
          f"{_hours(result.optimized.idle_minutes)} ({result.idle_reduction_pct:+.1f}%)")
    print(f"overtime {_hours(result.baseline.overtime_minutes)} -> "
          f"{_hours(result.optimized.overtime_minutes)} ({result.overtime_reduction_pct:+.1f}%)")
    print(f"on-time  {result.baseline.on_time_rate * 100:.0f}% -> "
          f"{result.optimized.on_time_rate * 100:.0f}% "
          f"({result.on_time_gain_pct_points:+.1f} pts)")
    print(f"emergency overtime {_hours(emergency.baseline_overtime_minutes)} -> "
          f"{_hours(emergency.optimized_overtime_minutes)} "
          f"({emergency.overtime_reduction_pct:+.1f}%) on {emergency.days} days")
    print(f"report written to {path}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
